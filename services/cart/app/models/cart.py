
import uuid

from datetime import datetime

from sqlalchemy import (
    CheckConstraint,
    DateTime,
    Index,
    String,
    Uuid,
    func,
    text,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base


class Cart(Base):
    __tablename__ = "carts"

    __table_args__ = (
        CheckConstraint(
            "user_id IS NOT NULL OR guest_id IS NOT NULL",
            name="ck_cart_has_owner",
        ),
        CheckConstraint(
            "status IN ('active', 'converted', 'abandoned')",
            name="ck_cart_status",
        ),
        Index(
            "uq_active_user_cart",
            "user_id",
            unique=True,
            postgresql_where=text(
                "user_id IS NOT NULL AND status = 'active'"
            ),
        ),
        Index(
            "uq_active_guest_cart",
            "guest_id",
            unique=True,
            postgresql_where=text(
                "guest_id IS NOT NULL AND status = 'active'"
            ),
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )

    # External Identity Service reference. No cross-service FK.
    user_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid(as_uuid=True),
        nullable=True,
        index=True,
    )

    # Opaque guest identifier generated by the backend.
    guest_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid(as_uuid=True),
        nullable=True,
        index=True,
    )

    status: Mapped[str] = mapped_column(
        String(20),
        default="active",
        nullable=False,
    )

    expires_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )

    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )

    items: Mapped[list["CartItem"]] = relationship(
        back_populates="cart",
        cascade="all, delete-orphan",
        passive_deletes=True,
    )
